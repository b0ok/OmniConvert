export function getCurrencyUnitDefinitions(rates: Record<string, number>): UnitDefinition[] {
  return CURRENCY_LIST.map((c) => {
    // base is USD: 1 USD has rates[c.code] of c.code
    // ratioToBase means: amount_in_USD = amount_in_c / rates[c.code]
    const rateToUsd = rates[c.code] || FALLBACK_USD_RATES[c.code] || 1;
    return {
      id: c.code,
      name: c.name,
      symbol: c.symbol,
      category: 'currency',
      ratioToBase: 1 / rateToUsd,
      popular: c.popular,
      flag: c.flag,
      country: c.country,
      description: `${c.country} (${c.code})`
    };
  });
}
